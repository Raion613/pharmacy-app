// AI の代わりに固定の結果を返す所。このアプリで AI を使う所はここだけにまとめた。
// 本物にするなら、この2つの関数の中で外部の API（音声認識・画像の文字読み取り）を呼ぶ。呼ぶ側は変えなくてよい。
//   transcribe   … 服薬指導の会話の音声 → 文字。kusudamaクラウド薬歴では録音すると AI が文字起こしする
//   readLabSheet … 検査結果の用紙の写真 → 検査項目と値。kusudamaクラウド薬歴ではタブレットで撮ると項目に値が入る
// 音声と画像はサーバーに送っていない（送っても使わないため）。画面からは長さ・ファイル名だけを受け取る。

// 固定の会話。薬の名前だけ、その来局の処方から入れる（会話から患者メモを拾う・下書きを作る流れを試せるように、
// 既往歴・併用薬・残薬・副作用の訴えが1つずつ出てくる）
export function transcribe({ drugNames }) {
  const first = drugNames[0] ?? "お薬";
  const second = drugNames[1];
  return [
    `薬剤師：今日は${first}${second ? `と${second}` : ""}が出ています。前回からお変わりありませんか。`,
    "患者：だいたい変わりないです。ここ1週間くらい、朝に少し胃がもたれます。",
    "薬剤師：お薬は飲み忘れずに飲めていますか。",
    "患者：昼の分をたまに飲み忘れます。2回分くらい残っています。",
    "薬剤師：ほかの病院のお薬や、市販のお薬、サプリメントは飲んでいますか。",
    "患者：ドラッグストアで買った胃腸薬をときどき飲んでいます。",
    "薬剤師：ほかに治療中の病気はありますか。",
    "患者：去年から整形外科で腰痛の治療をしています。",
    "薬剤師：分かりました。胃のもたれが続くようなら、次の受診のときに先生に伝えてください。",
  ].join("\n");
}

